#!/usr/bin/env python3
"""Translate an untyped TPTP problem (cnf and/or fof) into a Lean 4 *statement* of
satisfiability.

    python3 checker/tptp2lean.py PROBLEM.p  > Statement.lean

The problem is first normalised by Geoff's tptp4X (-x -umachine: includes expanded,
one formula per line) and then parsed by checker/tptp.py.  The output defines
    structure Sig (M : Type) where  <one field per function/predicate symbol>
    def Holds {M} (I : Sig M) : Prop := <conjunction of all formulas>
    def SatisfiableIn.{u} : Prop := ∃ (M : Type u) (I : Sig M), Nonempty M ∧ Holds I
    (Satisfiable = SatisfiableIn.{0}, Satisfiable1 = SatisfiableIn.{1}; any model suffices)
cnf clauses are universally closed; a conjecture is included *negated*, so for a
problem with a conjecture `Satisfiable` means CounterSatisfiable.  TPTP = is Lean =.
A model file then proves `theorem sat : TPTP.Satisfiable`.  This translator is the
only trusted part besides Lean itself, so it is kept deliberately small.
Symbols get a prefix (f_, c_, p_) so they cannot clash with Lean keywords; a name that is not a plain
identifier (a quoted 'X', a number, a "distinct object") is written with Lean's «...» quoting.
TPTP semantics of defined terms (TPTP SyntaxBNF): numbers are interpreted as themselves, so numbers with
different values are unequal ("1 != 2 is an implicit axiom"); distinct objects ("...") are interpreted as
themselves, so different ones are unequal. These implicit axioms are added as the first conjunct of Holds.
(tptp4X already identifies 'abc' with abc.)
"""
import os, re, subprocess, sys
from fractions import Fraction
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tptp

ROOT = os.environ.get("TPTP", "TPTP")


def formulas(problem):
    env = dict(os.environ, TPTP=os.path.abspath(ROOT))
    out = subprocess.run([os.path.join(ROOT, "Scripts", "tptp4X"), "-x", "-umachine", problem],
                         capture_output=True, text=True, env=env, check=True).stdout
    items = tptp.Parser(tptp.tokenize(out, problem), problem).tptp_input()
    for it in items:
        if it[0] != "formula" or it[1] not in ("cnf", "fof"):
            sys.exit(f"unsupported item: {it[:3]}")
        _, lang, name, role, ast, _, _ = it
        yield lang, name, role, ast


def main(problem):
    fs = list(formulas(problem))
    syms = set()
    for lang, _, _, ast in fs:
        for x in (ast if lang == "cnf" else [ast]):
            tptp.symbols(x, syms)
    kinds = {}
    for n, ar, k in syms:
        if kinds.setdefault(n, (ar, k)) != (ar, k):
            sys.exit(f"symbol {n} used with two arities/kinds")

    path = {}                       # symbol -> sub-structure prefix (for large signatures)

    def fname(n, ar, k):
        full = ("p_" if k == "pred" else "c_" if ar == 0 else "f_") + n
        return full if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", full) else "«" + full + "»"

    NUM = re.compile(r"[+-]?[0-9]+(?:/[0-9]+|\.[0-9]+(?:[Ee][+-]?[0-9]+)?|[Ee][+-]?[0-9]+)?")
    def numval(n):
        if "/" in n: return Fraction(n)
        return Fraction(n) if re.fullmatch(r"[+-]?[0-9]+", n) else Fraction(float(n)).limit_denominator(10**18) if "e" in n.lower() else Fraction(n)
    dobjs = sorted(n for n, (ar, k) in kinds.items() if ar == 0 and k == "fun" and n.startswith('"'))
    nums = sorted(n for n, (ar, k) in kinds.items() if ar == 0 and k == "fun" and NUM.fullmatch(n))
    for n, (ar, k) in kinds.items():
        if (n.startswith('"') or NUM.fullmatch(n)) and (ar, k) != (0, "fun"):
            sys.exit(f"defined term {n} used as a function or predicate")

    def t(x):
        if x[0] == "var":
            return "V" + x[1]
        s = "I." + path.get(x[1], "") + fname(x[1], len(x[2]), "fun")
        return s if not x[2] else "(" + s + " " + " ".join(t(a) for a in x[2]) + ")"

    def fm(f):
        k = f[0]
        if k == "pred":
            return "(I." + path.get(f[1], "") + fname(f[1], len(f[2]), "pred") + "".join(" " + t(a) for a in f[2]) + ")" \
                if f[2] else "I." + path.get(f[1], "") + fname(f[1], 0, "pred")
        if k == "eq": return f"({t(f[1])} = {t(f[2])})"
        if k == "true": return "True"
        if k == "false": return "False"
        if k == "not": return f"(¬ {fm(f[1])})"
        if k in ("and", "or"):
            if not f[1]: return "True" if k == "and" else "False"
            return "(" + (" ∧ " if k == "and" else " ∨ ").join(fm(g) for g in f[1]) + ")"
        if k in ("all", "ex"):
            q = "∀" if k == "all" else "∃"
            return f"({q} {' '.join('V' + v for v in f[1])} : M, {fm(f[2])})"
        a, b = fm(f[1]), fm(f[2])
        return {"imp": f"({a} → {b})", "iff": f"({a} ↔ {b})", "xor": f"(¬ ({a} ↔ {b}))",
                "nor": f"(¬ ({a} ∨ {b}))", "nand": f"(¬ ({a} ∧ {b}))"}[k]

    out = [f"-- Generated by checker/tptp2lean.py from {os.path.basename(problem)}; do not edit.",
           "set_option maxRecDepth 100000", "namespace TPTP", "universe u", ""]
    def field(n, ar, k):
        return f"  {fname(n, ar, k)} : " + "M → " * ar + ("Prop" if k == "pred" else "M")
    syml = sorted(kinds.items())
    CH = 200        # Lean structures cannot have arbitrarily many fields: constants go in parts
    consts = [(n, v) for n, v in syml if v == (0, "fun")] if len(syml) > CH else []
    rest = [(n, v) for n, v in syml if (n, v) not in consts]
    parts = [consts[i:i + CH] for i in range(0, len(consts), CH)]
    for i, part in enumerate(parts):
        out.append(f"structure Consts{i} (M : Type u) where")
        for n, (ar, k) in part:
            out.append(field(n, ar, k)); path[n] = f"k{i}."
        out.append("")
    out.append("structure Sig (M : Type u) where")
    for i in range(len(parts)):
        out.append(f"  k{i} : Consts{i} M")
    for n, (ar, k) in rest:
        out.append(field(n, ar, k))
    if not kinds:
        out.append("  dummy : Unit := ()")
    out += ["", "def Holds {M : Type u} (I : Sig M) : Prop :="]
    parts, conjs = [], []
    implicit = []
    for i, a in enumerate(dobjs):
        for b in dobjs[i + 1:]:
            implicit.append(f"(¬ ({t(('fun', a, []))} = {t(('fun', b, []))}))")
    for i, a in enumerate(nums):
        for b in nums[i + 1:]:
            op = "=" if numval(a) == numval(b) else "≠"
            implicit.append(f"({t(('fun', a, []))} = {t(('fun', b, []))})" if op == "=" else
                            f"(¬ ({t(('fun', a, []))} = {t(('fun', b, []))}))")
    if implicit:
        parts.append("  -- implicit TPTP axioms: distinct objects and numbers are interpreted as themselves\n  "
                     + "(" + " ∧ ".join(implicit) + ")")
    nconj = sum(1 for _, _, role, _ in fs if role == "conjecture")
    for lang, name, role, ast in fs:
        if lang == "cnf":
            body = fm(("or", ast))
            vs = sorted(tptp.clause_vars(ast))
            if vs:
                body = f"(∀ {' '.join('V' + v for v in vs)} : M, {body})"
        else:
            body = fm(ast)
        if role == "conjecture" and nconj > 1:
            conjs.append((name, body))
            continue
        if role == "conjecture":
            body = f"(¬ {body})"
        parts.append(f"  -- {name} ({role}{', negated' if role == 'conjecture' else ''})\n  {body}")
    if conjs:
        # TPTP conjoins several conjectures; the problem asks for a model of the axioms and not(c1 & c2 & ...)
        parts.append(f"  -- {', '.join(n for n, _ in conjs)} (conjectures, conjoined and negated)\n"
                     f"  (¬ ({' ∧ '.join(b for _, b in conjs)}))")
    out.append(" ∧\n".join(parts) if parts else "  True")
    out += ["", "def SatisfiableIn : Prop := ∃ (M : Type u) (I : Sig M), Nonempty M ∧ Holds I",
            "/-- a model in Type (e.g. built from Nat, Int, Rat) -/",
            "def Satisfiable : Prop := SatisfiableIn.{0}",
            "/-- a model in Type 1 (e.g. built from Mathlib's ZFSet.{0}) -/",
            "def Satisfiable1 : Prop := SatisfiableIn.{1}", "",
            "end TPTP", ""]
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
